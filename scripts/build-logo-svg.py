#!/usr/bin/env python3
"""Trace the pangolin logo into a real vector: public/logo.svg.

The mark is flat colour parted by transparent seams, so the alpha channel
carries the whole shape. Each plate, the head and the claws come out as their
own contour, and each is fitted with exact lines and arcs rather than being
left as a dense polyline — same treatment the wordmark got when it was traced
into a font.

Contours are filled with the nonzero rule, so outer shapes and holes are
given opposite winding; even-odd would punch holes where the head overlaps
the body.

Usage:  python3 scripts/build-logo-svg.py [--check]
Needs:  pillow
"""
import argparse
import math
import os
import sys

import numpy as np
from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from brandfont import vectorize as V  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "..", "docs", "images", "logo-source.png")
OUT = os.path.join(ROOT, "public", "logo.svg")

UPSAMPLE = 4          # sub-pixel accuracy comes from resampling the coverage
LEVEL = 128
FOREST_GREEN = "#0F6B43"


def trace(path):
    """Return (loops, size) — closed contours of the artwork, in source px."""
    src = Image.open(path).convert("RGBA")
    w, h = src.size
    alpha = Image.fromarray(np.asarray(src)[:, :, 3], "L")
    big = alpha.resize((w * UPSAMPLE, h * UPSAMPLE), Image.LANCZOS)
    g = [[float(v) for v in row] for row in np.asarray(big)]
    loops = V.extract_contours(g, LEVEL)
    return [[(x / UPSAMPLE, y / UPSAMPLE) for x, y in l] for l in loops], (w, h)


def to_path_data(prims, close=True):
    segs = V.to_segments(prims)
    if not segs:
        return ""
    d = [f"M{segs[0][1][0]:.1f} {segs[0][1][1]:.1f}"]
    for s in segs:
        if s[0] == "L":
            d.append(f"L{s[2][0]:.1f} {s[2][1]:.1f}")
        else:
            _, _, c1, c2, p1 = s
            d.append(f"C{c1[0]:.1f} {c1[1]:.1f} {c2[0]:.1f} {c2[1]:.1f} "
                     f"{p1[0]:.1f} {p1[1]:.1f}")
    if close:
        d.append("Z")
    return "".join(d)


COMPONENT = """/* Generated by scripts/build-logo-svg.py — do not edit by hand.
 * The pangolin mark, traced to vectors. Fills with currentColor so it picks
 * up the surrounding text colour and themes with the page. */
const VIEWBOX = "0 0 {w} {h}";
const RATIO = {w} / {h};

/* One path: fill-rule is applied per <path>, so the eye only reads as a hole
   if every contour shares an element. */
const D =
  "{d}";

type Props = {{ height?: number; className?: string; title?: string }};

export function LayrusMark({{ height = 32, className, title = "Layrus" }}: Props) {{
  return (
    <svg
      viewBox={{VIEWBOX}}
      width={{height * RATIO}}
      height={{height}}
      className={{className}}
      fill="currentColor"
      fillRule="nonzero"
      role="img"
      aria-label={{title}}
    >
      <path d={{D}} />
    </svg>
  );
}}
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="report how far the vector sits from the bitmap")
    args = ap.parse_args()

    loops, (w, h) = trace(SOURCE)
    loops = [l for l in loops if abs(V.signed_area(l)) > 6]   # drop specks

    # every contour comes out wound the same way, so holes (a contour nested
    # inside another — the eye) have to be reversed or nonzero fills them in
    holes = 0
    for loop in loops:
        depth = sum(1 for o in loops
                    if o is not loop and V.point_in_loop(o, loop[0]))
        if depth % 2:
            loop.reverse()
            holes += 1
    print(f"{len(loops)} contours from {w}x{h} ({holes} hole"
          f"{'s' if holes != 1 else ''})")

    paths, worst = [], 0.0
    for loop in sorted(loops, key=lambda l: -abs(V.signed_area(l))):
        prims = V.fit_loop(loop, corner_deg=50.0, tol=0.5, tol_global=1.2)
        d = to_path_data(prims)
        if not d:
            continue
        paths.append(d)
        if args.check:
            worst = max(worst, V.max_deviation(prims, loop))

    if args.check:
        print(f"worst distance from traced outline to bitmap: {worst:.3f}px "
              f"({100 * worst / w:.2f}% of the mark's width)")

    # All contours go in a SINGLE path element: fill-rule is applied per
    # <path>, so separate elements would each fill solid and the eye would
    # come back.
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" '
        f'role="img" aria-label="Layrus" fill="{FOREST_GREEN}">\n'
        f"<title>Layrus</title>\n"
        f'<path fill-rule="nonzero" d="{"".join(paths)}"/>\n'
        "</svg>\n"
    )
    with open(OUT, "w") as f:
        f.write(svg)
    print(f"wrote {os.path.relpath(OUT, ROOT)}  "
          f"({len(paths)} contours, {len(svg) / 1024:.1f} KB)")

    comp = os.path.join(ROOT, "components", "LayrusMark.tsx")
    with open(comp, "w") as f:
        f.write(COMPONENT.format(w=w, h=h, d="".join(paths)))
    print(f"wrote {os.path.relpath(comp, ROOT)}")


if __name__ == "__main__":
    main()
